// Fonction pour générer dynamiquement 30 questions (6 par trait)
export const getRandom30Questions = () => {
  const traits = ['O', 'C', 'E', 'A', 'N'];
  let selectedQuestions = [];

  traits.forEach((trait) => {
    // Filtrer les questions d'un trait
    const traitQuestions = questionsData.filter((q) => q.trait === trait);
    
    // Mélanger aléatoirement les questions du trait
    const shuffled = [...traitQuestions].sort(() => 0.5 - Math.random());
    
    // Sélectionner les 6 premières
    selectedQuestions.push(...shuffled.slice(0, 6));
  });

  // Mélanger l'ensemble des 30 questions pour ne pas poser tous les traits dans l'ordre
  return selectedQuestions.sort(() => 0.5 - Math.random());
};
